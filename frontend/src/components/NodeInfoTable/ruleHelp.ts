export function ruleHelper(rule: string): string {
    const name = rule.split(' ')[0];
    if (name === 'π') return 'This node hides some parts of the proof, you can unfold it.';
    const desc = RULES[name];
    return desc ? `${rule}\n\n${desc}` : rule;
}
